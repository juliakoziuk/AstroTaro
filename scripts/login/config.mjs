/** Чи лежить точка всередині картки (включно з лінією-рамкою). */
export function inCard(x, y, pad = 0) {
  const { x0, x1, y0, y1, r, arch } = CARD
  const X0 = x0 - 0.5 - pad
  const X1 = x1 + 0.5 + pad
  const Y0 = y0 - 0.5 - pad
  const Y1 = y1 + 0.5 + pad
  const R = r + pad
  if (x >= X0 && x <= X1 && y >= Y0 && y <= Y1) {
    const cx = Math.min(Math.max(x, X0 + R), X1 - R)
    const cy = Math.min(Math.max(y, Y0 + R), Y1 - R)
    if ((x - cx) ** 2 + (y - cy) ** 2 <= R * R) return true
  }
  // арка
  return (x - arch.cx) ** 2 + (y - arch.cy) ** 2 <= (arch.r + pad) ** 2 && y <= y0 + 0.5
}

