export const cardById = (id) => CARDS.find((c) => c.n === id)

export function cardOfDay(date) {
  const idx = (date.getFullYear() * 372 + date.getMonth() * 31 + date.getDate() * 7) % CARDS.length
  return CARDS[idx]
}

